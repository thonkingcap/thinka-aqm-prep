import { formulaHelp, FN_DOCS } from "./fnDocs.ts";
let fails = 0;
const ok = (c: boolean, m: string) => { if (!c) { fails++; console.log("FAIL", m); } };
const at = (s: string) => formulaHelp(s, s.length);
const h1 = at("=NORM.D");
ok(h1?.kind === "suggest" && h1.items[0].name === "NORM.DIST", "=NORM.D suggests NORM.DIST");
const h2 = at("=no");
ok(h2?.kind === "suggest" && h2.items.map((d) => d.name).join() === "NORM.DIST,NORM.S.DIST,NORM.INV,NORM.S.INV", "=no lists the four normal functions in class order");
const h3 = at("=NORM.DIST(B7,B5,");
ok(h3?.kind === "args" && h3.doc.name === "NORM.DIST" && h3.argIndex === 2, "third argument of NORM.DIST");
const h4 = at("=2*(1-T.DIST(");
ok(h4?.kind === "args" && h4.doc.name === "T.DIST" && h4.argIndex === 0, "T.DIST inside 2*(1-…)");
const h5 = at("=(AVERAGE(D5:D9)-10)/(STDEV.S(D5:D9)/SQRT(");
ok(h5?.kind === "args" && h5.doc.name === "SQRT", "innermost SQRT");
const h6 = at("=NORM.DIST(B7,B5,B6,TRUE)");
ok(h6 === null, "closed call shows nothing");
const h7 = at("=NORM.DIST(B");
ok(h7 === null || h7.kind === "args", "a cell reference does not open the list");
const h8 = at("=NORM.DIST(B7,B5,B6,T");
ok(h8?.kind === "suggest" && h8.items.some((d) => d.name === "T.DIST"), "T inside args suggests T functions");
ok(at("hello") === null, "plain text has no help");
ok(FN_DOCS.length >= 20, `catalog has ${FN_DOCS.length} functions`);
console.log(`${fails === 0 ? "PASS" : "FAILED"}: formula help, ${fails} failures`);
if (fails) process.exit(1);
